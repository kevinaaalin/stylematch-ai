import { createRequire } from "node:module";
import assert from "node:assert/strict";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(() => {
    localStorage.setItem("stylematch_active_plan_v1", "pro");
    if (localStorage.getItem("stylematch_local_mvp_v1")) return;
    localStorage.setItem("stylematch_local_mvp_v1", JSON.stringify({
      storage_schema_version: 4, projects: [{ project_id: "qa-case", id: "qa-case", name: "QA", reference_revisions: [{ revision_id: "qa-revision", image_url: "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j9V0AAAAASUVORK5CYII=", image_role: "ai_revision", version: 1, space: "客廳", status: "candidate" }] }],
      styleTests: [], isafeCases: [], notifications: [], auditLogs: [], jobs: [], point_balance: 100, point_ledger: [],
    }));
    const database = JSON.parse(localStorage.getItem("stylematch_local_mvp_v1"));
    database.projects[0].confirmed_reference_sets = [{ confirmed_reference_set_id: "set-qa", revision_ids: ["qa-revision"], images: [{ image_url: database.projects[0].reference_revisions[0].image_url, revision_id: "qa-revision" }] }];
    database.projects[0].active_confirmed_reference_set_id = "set-qa";
    database.projects.push({ ...database.projects[0], project_id: "qa-second", id: "qa-second", name: "QA second" });
    localStorage.setItem("stylematch_local_mvp_v1", JSON.stringify(database));
  });
  await page.goto("http://127.0.0.1:4173/#/ReferenceCanvas?project=qa-case&revision=qa-revision");
  await page.getByRole("link", { name: "接續 AI 生圖" }).click();
  await page.getByRole("link", { name: "接續提案圖確認" }).waitFor();
  assert.equal(await page.getByLabel("已存圖片版本").inputValue(), "qa-revision");
  await page.getByRole("link", { name: "接續提案圖確認" }).click();
  await page.getByRole("link", { name: "接續 AI 生圖" }).waitFor();
  await page.getByRole("region", { name: "最近成果" }).locator("select").selectOption(JSON.stringify(["qa-second", "qa-revision"]));
  await page.getByRole("link", { name: "開啟提案圖確認" }).click();
  await page.waitForURL(/project=qa-second/);
  assert.equal(await page.getByLabel("已存圖片版本").inputValue(), "qa-revision");
  assert.ok((await page.getByRole("link", { name: "接續 AI 生圖" }).getAttribute("href")).includes("project=qa-second"));
  const beforeBranch = await page.evaluate(() => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")));
  await page.getByRole("button", { name: "從此版本建立分支" }).click();
  await page.getByText("獨立候選分支已建立，未扣點；原版本保持不變。").waitFor();
  const afterBranch = await page.evaluate(() => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")));
  const previous = beforeBranch.projects.find((item) => item.project_id === "qa-second").reference_revisions;
  const updated = afterBranch.projects.find((item) => item.project_id === "qa-second").reference_revisions;
  assert.deepEqual(updated.slice(1), previous);
  assert.equal(updated[0].parent_asset_id, "qa-revision");
  assert.equal(updated[0].branch_id, updated[0].revision_id);
  assert.equal(updated[0].status, "candidate");
  assert.equal(afterBranch.point_balance, beforeBranch.point_balance);
  await page.goto("http://127.0.0.1:4173/#/ReferenceCanvas?project=qa-case&revision=missing");
  await page.getByText("交接圖片不存在、不相容或不屬於指定專案，請重新選擇來源。").waitFor();
  assert.equal(await page.getByLabel("已存圖片版本").inputValue(), "");
  assert.equal(await page.getByRole("link", { name: "接續 AI 生圖" }).count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.goto("http://127.0.0.1:4173/#/ReferenceCanvas?project=qa-case&revision=qa-revision");
  const balanceBefore = await page.evaluate(() => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")).point_balance);
  await page.getByRole("button", { name: "商業方案：扣點生成正式圖像提案" }).click();
  await page.getByText(/提案資料不足：/).waitFor();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")).point_balance), balanceBefore);
  await page.getByText("提案基本資料", { exact: true }).click();
  for (const [label, value] of [["室內坪數", "25"], ["空間配置", "客廳與兩房"], ["預算範圍", "100-200萬"], ["設計風格", "modern"]]) await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByRole("button", { name: "儲存提案資料" }).click();
  await page.getByText("提案資料已儲存，既有提案快照未變更。").waitFor();
  await page.getByRole("button", { name: "商業方案：扣點生成正式圖像提案" }).click();
  await page.getByRole("link", { name: "查看正式提案" }).waitFor();
  const proposalData = await page.evaluate(() => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")));
  assert.equal(proposalData.point_balance, balanceBefore - 30);
  assert.equal(proposalData.projects.find((item) => item.project_id === "qa-case").proposal_versions.length, 1);
  const beforeDraft = await page.evaluate(() => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")));
  await page.getByLabel("新工具草稿名稱").fill("Independent tool QA");
  await page.getByRole("button", { name: "建立工具草稿" }).click();
  await page.waitForURL((url) => url.hash.includes("project=") && !url.hash.includes("project=qa-"));
  await page.getByLabel("新工具草稿名稱").waitFor();
  const afterDraft = await page.evaluate(() => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")));
  const draft = afterDraft.projects.find((item) => item.project_name === "Independent tool QA");
  assert.equal(draft.workflow_only, true);
  assert.equal(draft.isafe_case_id, null);
  assert.equal(draft.twcid_match_id, null);
  assert.equal(draft.match_status, "not_requested");
  assert.equal(afterDraft.jobs.length, beforeDraft.jobs.length);
  assert.equal(afterDraft.point_balance, beforeDraft.point_balance);
  await page.goto(`http://127.0.0.1:4173/#/Workspace?project=${draft.project_id}`);
  await page.getByLabel("情境名稱", { exact: true }).fill("Budget QA");
  for (const [field, value] of Object.entries({ space: "客廳", category: "地坪", label: "鋪設", quantity: "2", unit_price: "100" })) {
    await page.getByLabel(`第1筆 ${field}`, { exact: true }).fill(value);
  }
  await page.getByRole("button", { name: "另存預算版本" }).click();
  await page.getByText("已儲存 v1，原版本未變更。").waitFor();
  await page.getByLabel("第1筆 unit_price", { exact: true }).fill("150");
  await page.getByRole("button", { name: "另存預算版本" }).click();
  await page.getByText("已儲存 v2，原版本未變更。").waitFor();
  const budgets = await page.evaluate((id) => JSON.parse(localStorage.getItem("stylematch_local_mvp_v1")).projects.find((item) => item.project_id === id).budget_scenarios, draft.project_id);
  assert.equal(budgets[0].total_cents, 30000);
  assert.equal(budgets[1].total_cents, 20000);
  assert.equal(budgets[0].parent_scenario_id, budgets[1].scenario_id);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.goto("http://127.0.0.1:4173/#/Workspace?project=missing-case");
  await page.getByRole("alert").filter({ hasText: "指定專案不存在" }).waitFor();
  assert.equal(await page.getByRole("button", { name: "開啟", exact: true }).count(), 3);
  for (const button of await page.getByRole("button", { name: "開啟", exact: true }).all()) assert.equal(await button.isDisabled(), true);
  await page.evaluate((id) => { location.hash = `/Workspace?project=${id}`; }, draft.project_id);
  await page.getByLabel("情境名稱", { exact: true }).waitFor();
  assert.equal(await page.getByRole("alert").filter({ hasText: "指定專案不存在" }).count(), 0);
  await page.goto("http://127.0.0.1:4173/#/ProposalReport?project=missing-case");
  await page.getByText("找不到指定專案或提案版本，請返回我的專案重新選擇。").waitFor();
  assert.deepEqual(errors, []);
  console.log("Browser handoff round trip, invalid source and mobile overflow checks passed.");
} finally { await browser.close(); }
