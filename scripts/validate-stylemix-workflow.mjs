import assert from 'node:assert/strict';
import { fuseStyleDNA, buildStyleMixPrompt } from '../src/lib/styleMixWorkflow.js';
const a = { id: 'a', source_ref: 'asset:a', dimensions: { color: { value: 'ivory', confidence: 0.9 } } };
const b = { id: 'b', source_ref: 'asset:b', dimensions: { color: { value: 'black', confidence: 0.8 } } };
const fusion = fuseStyleDNA({ a, b, globalWeight: 0.7 });
assert.equal(fusion.dimensions.color.contributions[0].weight, 0.7);
assert.equal(fusion.dimensions.color.contributions[1].source_ref, 'asset:b');
assert.equal(fusion.dimensions.geometry.requires_review, true);
assert.equal(fusion.governance_state_changed, false);
assert.equal(buildStyleMixPrompt(fusion, 'furniture').generation_status, 'not_started');
assert.throws(() => fuseStyleDNA({ a, b, globalWeight: NaN }));
assert.throws(() => fuseStyleDNA({ a, b, dimensionWeights: { typo: 0.5 } }));
assert.throws(() => buildStyleMixPrompt(fusion, 'unknown'));
assert.equal(fuseStyleDNA({ a, b, globalWeight: 0 }).dimensions.color.contributions.length, 1);
assert.equal(a.dimensions.color.value, 'ivory');
const image = { ...a, requires_human_confirmation: true, dimensions: { color: { value: 'ivory', confidence: 0.2 } } };
assert.throws(() => buildStyleMixPrompt(fuseStyleDNA({ a: image, b }), 'interior'), /confirmation/);
const reviewed = fuseStyleDNA({ a: { ...image, human_confirmed: true }, b });
assert.match(buildStyleMixPrompt(reviewed, 'interior').prompt, /ivory/);
assert.equal(reviewed.dimensions.color.contributions[0].confidence, 0.2);
console.log('StyleMix workflow contract checks passed');
