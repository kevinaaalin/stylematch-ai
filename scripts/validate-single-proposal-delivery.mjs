import assert from 'node:assert/strict';
import { imageResultTransaction } from '../src/lib/imageResultTransaction.js';
import { canDeliverLocalSingleProposal } from '../src/lib/singleProposalPolicy.js';
globalThis.location = { hostname: '127.0.0.1' };
const p = { project_id: 'p', payment: { plan_id: 'single', status: 'paid_test' }, proposal_media: { space_photos: { living_room: [], balcony: [] } }, reference_revisions: [] };
const db = { projects: [p], point_balance: 0, point_ledger: [] };
const data = { image_url: '/valid.png', source_task_id: 'task', task_status: 'completed', completion_room: 'living_room', completion_slot: 0, output_sha256: 'hash' };
const pay = { idempotencyKey: 'single-1', type: 'proposal_space_completion', cost: 0 };
const ids = { revisionId: 'r1', transactionId: 't1', at: '2026-10-05' };
const result = imageResultTransaction(db, 'p', data, pay, ids);
assert.equal(result.balance, 0);
assert.equal(result.transaction.points, 0);
assert.equal(result.database.projects[0].reference_revisions.length, 1);
assert.equal(imageResultTransaction(result.database, 'p', data, pay, ids).reused, true);
assert.throws(() => imageResultTransaction(result.database, 'p', data, { ...pay, idempotencyKey: 'duplicate' }, ids));
assert.throws(() => imageResultTransaction(db, 'p', { ...data, completion_room: 'balcony' }, pay, ids));
assert.throws(() => imageResultTransaction(db, 'p', data, { ...pay, type: 'image' }, ids));
p.payment.status = 'unpaid';
assert.throws(() => imageResultTransaction(db, 'p', data, pay, ids));
p.payment.status = 'paid_test';
p.single_proposal_delivery = { version_id: 'done' };
assert.equal(canDeliverLocalSingleProposal(p), false);
delete p.single_proposal_delivery;
globalThis.location.hostname = 'example.com';
assert.throws(() => imageResultTransaction(db, 'p', data, pay, ids));
console.log('PASS included local delivery: zero balance, no debit, retry, duplicate slot, balcony, unpaid, fulfilled and public guards');
