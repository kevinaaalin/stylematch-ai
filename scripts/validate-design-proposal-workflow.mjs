import assert from 'node:assert/strict';
import { runDesignProposalWorkflow } from '../src/lib/designProposalWorkflow.js';
import { getFrozenProposalDocument } from '../src/lib/proposalDocument.js';
const options = { versionId: 'v1', at: '2026-09-26T00:00:00Z' };
assert.throws(() => runDesignProposalWorkflow({}, options));
assert.equal(runDesignProposalWorkflow({ id: 'p' }, options).status, 'incomplete');
const project = { id: 'p', project_name: 'test', square_footage: 30, room_layout: 'living room', budget_range: '100-200萬', primary_style: 'modern', reference_revisions: [{ revision_id: 'r1', image_url: 'fixture' }], active_confirmed_reference_set_id: 's1', confirmed_reference_sets: [{ confirmed_reference_set_id: 's1', revision_ids: ['r1'], images: [{ revision_id: 'r1', image_url: 'fixture' }] }] };
const result = runDesignProposalWorkflow(project, options);
assert.equal(result.status, 'draft');
assert.equal(result.formal_approval_required, true);
const humanistic = runDesignProposalWorkflow({ ...project, primary_style: 'humanistic' }, options);
assert.ok(humanistic.proposal.materials.every(item => !item.suggestion.includes('陶器') && !item.suggestion.includes('棉麻')));
assert.equal(result.proposal.spaces[0].url, 'fixture');
assert.equal(result.proposal.spaces[0].revision_id, 'r1');
assert.equal(result.version.project_snapshot.proposal_document.delivery.setId, 's1');
assert.equal(result.version.project_snapshot.proposal_document.delivery.adopted.length, 1);
assert.equal(result.version.project_snapshot.proposal_document.version_id, 'v1');
assert.equal(project.proposal_versions, undefined);
assert.throws(() => runDesignProposalWorkflow({ ...project, proposal_versions: [result.version] }, options));
assert.equal(runDesignProposalWorkflow({ ...project, reference_revisions: [] }, options).status, 'incomplete');
const corrupted = structuredClone(project);
corrupted.confirmed_reference_sets[0].images[0].image_url = 'different-image';
assert.equal(runDesignProposalWorkflow(corrupted, options).status, 'incomplete');
const next = runDesignProposalWorkflow({ ...project, proposal_workflow: result, proposal_versions: [result.version] }, { ...options, versionId: 'v2' });
assert.equal(next.version.version, 2);
assert.equal(next.version.parent_version_id, 'v1');
assert.equal(next.version.project_snapshot.proposal_workflow, undefined);
const historyProject = { ...project, proposal_versions: [next.version, result.version] };
const beforeBranch = JSON.stringify(historyProject);
const branch = runDesignProposalWorkflow(historyProject, { ...options, versionId: 'v3', parentVersionId: 'v1' });
assert.equal(branch.version.parent_version_id, 'v1');
assert.equal(branch.version.version, 3);
assert.equal(JSON.stringify(historyProject), beforeBranch);
for (const parentVersionId of ['missing', '', null, 1]) {
  assert.throws(() => runDesignProposalWorkflow(historyProject, { ...options, versionId: 'v3', parentVersionId }));
}
assert.throws(() => runDesignProposalWorkflow(project, { ...options, parentVersionId: 'v1' }));
assert.throws(() => runDesignProposalWorkflow({ ...project, proposal_versions: {} }, options));
assert.throws(() => runDesignProposalWorkflow({ ...historyProject, id: 'foreign' }, { ...options, versionId: 'v3' }));
assert.throws(() => runDesignProposalWorkflow({ ...project, proposal_versions: [result.version, result.version] }, { ...options, versionId: 'v3' }));
const exportProject = { ...project, proposal_versions: [next.version, result.version] };
const exported = getFrozenProposalDocument(exportProject, 'v1');
assert.equal(exported.version_id, 'v1');
exported.proposal.title = 'mutated';
assert.notEqual(getFrozenProposalDocument(exportProject, 'v1').proposal.title, 'mutated');
assert.throws(() => getFrozenProposalDocument(exportProject, 'unknown'));
assert.throws(() => getFrozenProposalDocument({ ...exportProject, id: 'other' }, 'v1'));
assert.throws(() => getFrozenProposalDocument({ ...project, proposal_versions: [result.version, result.version] }, 'v1'));
const foreignSnapshot = structuredClone(result.version);
foreignSnapshot.project_snapshot.id = 'foreign';
assert.throws(() => getFrozenProposalDocument({ ...project, proposal_versions: [foreignSnapshot] }, 'v1'));
assert.throws(() => getFrozenProposalDocument(null, 'v1'));
assert.throws(() => getFrozenProposalDocument(exportProject, ''));
console.log('Design proposal workflow checks passed');
