import { readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative, resolve, sep } from "node:path";
import { STYLE_CATALOG } from "../src/data/styleCatalog.js";

const root = resolve("public/style-reference-db");
const output = resolve("src/data/styleTestImageManifest.js");
const imagePattern = /\.(?:jpe?g|png|webp)$/i;
const canonicalRoot = join(root, "synthetic", "comfyui");
const taiwanRoot = join(root, "synthetic", "comfyui-taiwan-25");
const taiwanAliases = {
  french: "european_classic",
  loft: "industrial",
  avant_garde: "futurism",
  mediterranean: "south_french_mediterranean",
};
const knownStyleIds = [...new Set([...STYLE_CATALOG.map((style) => style.id), ...Object.keys(taiwanAliases)])]
  .sort((a, b) => b.length - a.length);

function filesIn(folder) {
  if (!statSafe(folder)) return [];
  return readdirSync(folder, { withFileTypes: true })
    .flatMap((entry) => entry.isDirectory() ? filesIn(join(folder, entry.name)) : [join(folder, entry.name)])
    .filter((file) => imagePattern.test(extname(file)))
    .sort((a, b) => a.localeCompare(b, "zh-Hant"));
}

function statSafe(path) {
  try { return statSync(path); } catch { return null; }
}

function publicUrl(file) {
  // Keep this relative to the deployed app root. A leading slash would bypass
  // Vite's GitHub Pages base path (`/stylematch-ai/`) and request the domain root.
  return relative(resolve("public"), file).split(sep).map(encodeURIComponent).join("/");
}

function styleIdFromFolder(folderName) {
  const matched = knownStyleIds.find((styleId) => folderName.endsWith(`_${styleId}`));
  if (!matched) throw new Error(`Unknown style folder: ${folderName}`);
  return matched;
}

function matchingFolders(folderRoot, targetStyleId, aliases = {}) {
  return readdirSync(folderRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .filter((entry) => (aliases[styleIdFromFolder(entry.name)] || styleIdFromFolder(entry.name)) === targetStyleId)
    .map((entry) => join(folderRoot, entry.name));
}

const questions = STYLE_CATALOG.map((style, index) => {
  const taiwanFolders = matchingFolders(taiwanRoot, style.id, taiwanAliases);
  const canonicalFolders = matchingFolders(canonicalRoot, style.id);
  const selectedFolders = taiwanFolders.length ? taiwanFolders : canonicalFolders;
  const synthetic = selectedFolders.flatMap(filesIn);
  const selected = synthetic[index % synthetic.length];
  if (!selected) throw new Error(`No synthetic ComfyUI reference image found for style: ${style.id}`);
  const sourceLibrary = taiwanFolders.length ? "comfyui-taiwan-25" : "comfyui-30-fallback";
  return {
    id: index + 1,
    src: publicUrl(selected),
    variants: synthetic.map(publicUrl),
    style: [style.id],
    styles: [style.id],
    primary_style: style.id,
    style_name: style.name,
    source: "synthetic_comfyui",
    source_library: sourceLibrary,
    source_categories: selectedFolders.map((folder) => styleIdFromFolder(folder)),
  };
});

const content = `// Generated by scripts/build-style-test-image-manifest.mjs. Do not edit manually.\n` +
  `export const STYLE_TEST_IMAGE_MANIFEST_VERSION = "stylematch.style-test-images.r9.taiwan25-primary-v1";\n` +
  `export const styleTestImages = ${JSON.stringify(questions, null, 2)};\n`;
writeFileSync(output, content, "utf8");
console.log(`style test manifest generated: ${questions.length} styles`);
