import assert from 'node:assert/strict';
import { proposalDeliveryStatus } from '../src/lib/proposalDeliveryStatus.js';
const project = { project_id: 'p', proposal_media: { space_photos: { living_room: [], balcony: [] } }, reference_revisions: [] };
assert.equal(proposalDeliveryStatus(project).missing, 4);
assert.equal(proposalDeliveryStatus(project).rooms, 1);
assert.equal(proposalDeliveryStatus({}).state, 'needs_scope');
project.reference_revisions = Array.from({length:4}, (_,i) => ({ project_id:'p', completion_room:'living_room', task_status:'completed', source_task_id:`t${i}`, image_url:`/${i}.png`, status:'candidate' }));
assert.equal(proposalDeliveryStatus(project).state, 'needs_proposal');
assert.equal(proposalDeliveryStatus(project).generated, 4);
project.proposal_versions = [{ version_id: 'v1', version: 1, project_snapshot: { project_id: 'p' } }];
assert.equal(proposalDeliveryStatus(project).state, 'needs_proposal');
project.proposal_versions[0].project_snapshot.proposal_document = { version_id: 'v1', project_id: 'p', proposal: {}, delivery: {} };
assert.equal(proposalDeliveryStatus(project).state, 'saved');
assert.equal(proposalDeliveryStatus(project).versionId, 'v1');
project.proposal_versions[0].project_snapshot.project_id = 'other-project';
assert.equal(proposalDeliveryStatus(project).state, 'needs_proposal');
assert.equal(proposalDeliveryStatus(project).versionId, null);
project.proposal_versions.push({ ...project.proposal_versions[0] });
assert.equal(proposalDeliveryStatus(project).versionId, null);
console.log('PASS delivery progress: scope, balcony exemption, images, saved version and invalid snapshot rejection');
