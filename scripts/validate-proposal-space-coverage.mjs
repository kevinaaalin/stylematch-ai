import assert from 'node:assert/strict';
import {proposalSpaceCoverage} from '../src/lib/proposalSpaceCoverage.js';
const project={project_id:'p',proposal_media:{space_photos:{living_room:['/a','/b'],study_room:[],floor_plan:['/plan']}},reference_revisions:[]};
const revision={project_id:'p',source_photo_room:'living_room',source_image_url:'/a',source_task_id:'task',image_url:'/generated',status:'candidate'};
project.reference_revisions=[revision,{...revision},{...revision,project_id:'foreign',source_image_url:'/b',image_url:'/foreign'},{...revision,status:'archived',source_image_url:'/b',image_url:'/archived'},{...revision,source_task_id:null,source_image_url:'/b',image_url:'/unbound'}];
const before=JSON.stringify(project),result=proposalSpaceCoverage(project);
assert.equal(result.length,2);assert.equal(result[0].covered_original_count,1);assert.equal(result[0].missing_original_count,1);
assert.equal(result[0].generated_reference_count,1);assert.equal(result[0].additional_reference_count,3);
assert.equal(result[1].original_count,0);assert.equal(result[1].additional_reference_count,4);
assert.equal(JSON.stringify(project),before);
project.reference_revisions=Array.from({length:4},(_,i)=>({...revision,image_url:'/output-'+i}));
assert.equal(proposalSpaceCoverage(project)[0].additional_reference_count,0);
assert.equal(proposalSpaceCoverage(project)[0].direction_quality_status,'NOT_VERIFIED');
assert.equal(proposalSpaceCoverage(project)[0].missing_original_count,1);
project.proposal_media.space_photos.living_room=Array(5).fill('/a');
assert.equal(proposalSpaceCoverage(project)[0].upload_limit_exceeded,true);
assert.equal(project.proposal_media.space_photos.living_room.length,5);
assert.deepEqual(proposalSpaceCoverage(),[]);
console.log('PASS: per-space coverage, zero photos, duplicate outputs, foreign/archived sources, immutable inputs and no count-to-panorama approval.');
